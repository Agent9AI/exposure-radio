def write_wav_f32(path, x):
    data = np.ascontiguousarray(x.T, dtype="<f4").tobytes()
    fmt = struct.pack("<HHIIHH", 3, 2, SR, SR * 8, 8, 32)    # IEEE float, stereo
    with open(path, "wb") as f:
        f.write(b"RIFF" + struct.pack("<I", 4 + 8 + len(fmt) + 8 + len(data)) + b"WAVE")
        f.write(b"fmt " + struct.pack("<I", len(fmt)) + fmt)
        f.write(b"data" + struct.pack("<I", len(data)) + data)


def _ffmpeg(args):
    r = subprocess.run(["ffmpeg", "-hide_banner", "-nostats", *args], capture_output=True, text=True)
    if r.returncode != 0:
        raise RuntimeError(f"ffmpeg failed: {' '.join(args)}\n{r.stderr[-2000:]}")
    return r.stderr


def _last_json(text):
    return json.loads(text[text.rfind("{"):text.rfind("}") + 1])


def master(x, wav, mp3, target, tp, meta, limit=True, lra=20, drive=3.0):
    """Pre-limit until linear loudnorm can hit target, then two-pass loudnorm -> MP3."""
    x = normalize(x, 0.9)
    for _ in range(8):
        y = limiter(normalize(x, 10 ** (drive / 20)), 0.89) if limit else x
        write_wav_f32(wav, y)
        m = _last_json(_ffmpeg(["-i", str(wav), "-af",
                                f"loudnorm=I={target}:TP={tp}:LRA={lra}:print_format=json",
                                "-f", "null", "-"]))
        over = float(m["input_tp"]) + target - float(m["input_i"]) - (tp - 0.25)
        if over <= 0 or not limit:
            break
        drive += over + 0.25
    af = (f"loudnorm=I={target}:TP={tp}:LRA={lra}:measured_I={m['input_i']}:"
          f"measured_TP={m['input_tp']}:measured_LRA={m['input_lra']}:"
          f"measured_thresh={m['input_thresh']}:offset={m['target_offset']}:"
          f"linear=true:print_format=json")
    tags = []
    for k, v in meta.items():
        tags += ["-metadata", f"{k}={v}"]
    out = _last_json(_ffmpeg(["-y", "-i", str(wav), "-af", af, "-ar", str(SR), "-ac", "2",
                              "-c:a", "libmp3lame", "-b:a", "160k", "-map_metadata", "-1",
                              "-id3v2_version", "3", *tags, "-fflags", "+bitexact",
                              "-flags:a", "+bitexact", str(mp3)]))
    return {"limiter_drive_db": round(drive, 2), "mode": out.get("normalization_type")}


def measure(mp3):
    txt = _ffmpeg(["-i", str(mp3), "-af", "ebur128=peak=true", "-f", "null", "-"])
    txt = txt[txt.rfind("Summary:"):]
    num = r"(-?(?:\d+\.\d+|inf))"
    dur = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration",
                          "-of", "csv=p=0", str(mp3)], capture_output=True, text=True).stdout
    return {"lufs": float(re.search(r"I:\s+" + num + " LUFS", txt).group(1)),
            "lra": float(re.search(r"LRA:\s+" + num + " LU", txt).group(1)),
            "true_peak": float(re.search(r"Peak:\s+" + num + " dBFS", txt).group(1)),
            "duration": round(float(dur), 2)}


BANDS = (("sub", 25, 120), ("low", 120, 400), ("mid", 400, 2000), ("pres", 2000, 6000),
         ("air", 6000, 16000))


def band_levels(x):
    """Energy per band in dB relative to the whole 20 Hz-20 kHz band."""
    m = x.mean(0) if x.ndim == 2 else x
    P = np.abs(np.fft.rfft(m, fft_len(m.size))) ** 2
    f = np.fft.rfftfreq(fft_len(m.size), 1 / SR)
    tot = P[(f >= 20) & (f <= 20000)].sum() + 1e-20
    return {n: round(float(10 * np.log10(P[(f >= lo) & (f < hi)].sum() / tot + 1e-12)), 1)
            for n, lo, hi in BANDS}


