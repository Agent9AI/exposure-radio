def render_track(cfg):
    """Arrange and mix one instrumental. Returns (stereo mix, 808 stem)."""
    rng = np.random.default_rng(cfg["seed"])
    beat = 60.0 / cfg["bpm"]
    step, barlen = beat / 4, 4 * beat
    key, chords = cfg["key_root"], cfg["chords"]
    song = sum(s["bars"] for s in cfg["sections"]) * barlen
    N = int((song + 4.5) * SR)

    kick = make_kick(rng, **cfg["kick"])
    boom = make_kick(rng, f_hi=120.0, f_lo=38.0, tau=0.08, decay=0.9, click=0.3, length=2.5)
    snare = normalize(0.75 * make_clap(rng, 0.7) + 0.55 * make_snare(rng, 0.7))
    hats = [[make_hat(rng, 0.032, r) for _ in range(3)] for r in (1.0, 1.12, 1.26)]
    ohat = make_hat(rng, 0.2)
    crash = make_hat(rng, 0.85, 0.8, tone=4200.0, length=2.5)
    ir = make_ir(rng)

    drums, verb_send, fx = (np.zeros((2, N)) for _ in range(3))
    lead_bus, counter_bus = np.zeros((2, N)), np.zeros((2, N))
    pad_bus = np.zeros((2, N // 4 + 2))
    bright = np.full(N, 2.0)
    bass_notes, kick_times = [], []
    hat_n = 0

    def hit_kick(t):
        place(drums, kick, t, 0.85)
        kick_times.append(t)

    def hit_snare(t, g=1.0):
        place(drums, snare, t, 0.6 * g)
        place(verb_send, snare, t, 0.35 * g)

    bar0 = 0
    for sec in cfg["sections"]:
        t0, t1 = bar0 * barlen, (bar0 + sec["bars"]) * barlen
        a, b = int(t0 * SR), int(t1 * SR)
        bl0, bl1 = sec.get("bright", (2.0, 2.0))
        bright[a:b] = np.linspace(bl0, bl1, b - a)
        bright[b:] = bl1
        if sec.get("crash"):
            place(drums, crash, t0, 0.2, pan=-0.2)
            place(drums, boom, t0, 0.55)
            kick_times.append(t0)
        if sec.get("riser"):
            rdur = sec["riser"] * barlen
            place(fx, make_riser(rng, rdur), t1 - rdur, 0.13)
        for i in range(sec["bars"]):
            bar = bar0 + i
            tb = bar * barlen
            chord = chords[bar % len(chords)]
            last = i == sec["bars"] - 1
            cut = 12 if (last and sec.get("stop")) else 99

            pat = cfg["bass"].get(sec.get("bass"))
            if pat:
                for st, ln, iv, gl in pat[i % len(pat)]:
                    if st >= cut:
                        continue
                    ln = min(ln, cut - st)
                    bass_notes.append((tb + st * step, ln * step, bass_midi(key - 36, chord) + iv, gl))
                    if sec.get("kick") and not gl:
                        hit_kick(tb + st * step)

            if sec.get("snare"):
                if sec.get("roll") and last:
                    roll = [0, 4, 6, 8, 9, 10, 10.5, 11, 11.5] + ([] if sec.get("stop") else
                                                                  [12, 13, 14, 14.5, 15, 15.5])
                    for j, st in enumerate(roll):
                        hit_snare(tb + st * step, 0.35 + 0.65 * j / (len(roll) - 1))
                else:
                    hit_snare(tb + 8 * step)
                    if cfg["ghost"] and bar % 4 == 3 and sec.get("kick"):
                        hit_snare(tb + cfg["ghost"] * step, 0.45)

            if sec.get("hats"):
                for off, vel, pi in hat_events(rng, cfg["hat_rolls"], sec["hats"], i % 4 == 3):
                    if off * 4 >= cut:
                        continue
                    place(drums, hats[pi][hat_n % 3], tb + off * beat, 0.17 * vel, pan=0.18)
                    hat_n += 1
                if sec["hats"] in ("main", "busy") and i % 2 == 1:
                    place(drums, ohat, tb + 6 * step, 0.1, pan=-0.15)

            motif = cfg["motifs"].get(sec.get("lead"))
            if motif:
                for st, ln, k in motif[i % len(motif)]:
                    note = lead_note(cfg["lead"], chord_tone(key, chord, k), ln * step, rng)
                    place(lead_bus, note, tb + st * step, cfg["lead_gain"])
            if sec.get("counter"):
                cm = cfg["motifs"]["counter"]
                for st, ln, k in cm[i % len(cm)]:
                    note = lead_note(cfg["counter"], chord_tone(key, chord, k) + cfg["counter_oct"],
                                     ln * step, rng)
                    place(counter_bus, note, tb + st * step, cfg["counter_gain"])
            place(pad_bus, pad_chord(pad_voicing(key, chord), barlen, rng), tb, 0.12, sr=PAD_SR)
        bar0 += sec["bars"]

    # final resolving hit on the tonic, then let it ring out
    tonic = chords[0]
    place(drums, boom, song, 0.6)
    place(drums, crash, song, 0.2, pan=-0.2)
    kick_times.append(song)
    bass_notes.append((song, 2.6, bass_midi(key - 36, tonic), 0))
    for k in (0, 3):
        place(lead_bus, lead_note(cfg["lead"], chord_tone(key, tonic, k), 1.6, rng), song,
              cfg["lead_gain"])
    place(pad_bus, pad_chord(pad_voicing(key, tonic), 2.0, rng, release=0.6), song, 0.12, sr=PAD_SR)

    bass = render_808(bass_notes, N, **cfg["b808"]) * duck(N, kick_times, 0.35, 0.05)
    lead = morph(filt_many(lead_bus, [hp(140) + lp4(650), hp(140) + lp4(2200),
                                      hp(140) + lp(9500, 0.8)]), bright)
    sc = duck(N, kick_times, 0.45, 0.11)
    lead *= sc
    counter = filt(counter_bus, hp(250) + lp(7000)) * sc
    pad = filt(upsample(pad_bus, N), hp(120) + lp4(1100)) * duck(N, kick_times, 0.6, 0.16)
    verb = convolve(0.3 * lead + 0.35 * counter + 0.5 * pad + verb_send, ir)
    delay = pingpong(lead + 0.5 * counter, 0.75 * beat)
    drums = np.tanh(1.3 * drums) / 1.3
    mix = drums + 0.62 * bass[None, :] + lead + counter + pad + 0.3 * verb + 0.2 * delay + fx
    mix = filt(mix, hp(24))
    end = int((song + 4.0) * SR)
    mix = mix[:, :end]
    k = int(2.0 * SR)
    mix[:, -k:] *= np.cos(np.linspace(0, np.pi / 2, k)) ** 2
    return mix, bass[:end]


def render_bed(cfg):
    """Low-key speech bed, rendered so the end wraps seamlessly into the start."""
    rng = np.random.default_rng(cfg["seed"])
    beat = 60.0 / cfg["bpm"]
    step, barlen = beat / 4, 4 * beat
    key, chords = cfg["key_root"], cfg["chords"]
    L = cfg["bars"] * barlen
    Ls, N = int(round(L * SR)), int((L + 4.0) * SR)
    soft_kick = filt(make_kick(rng, f_hi=110.0, f_lo=45.0, tau=0.03, decay=0.18, click=0.0), lp4(180))
    tick = make_hat(rng, 0.018, 1.2, tone=9500.0)
    ir = make_ir(rng, rt60=2.6, length=3.0, predelay=0.02)
    bell_bus, drums = np.zeros((2, N)), np.zeros((2, N))
    pad_bus = np.zeros((2, N // 4 + 2))
    bass_notes, kick_times = [], []
    span = cfg["chord_bars"] * barlen
    for c in range(cfg["bars"] // cfg["chord_bars"]):
        t0, chord = c * span, chords[c % len(chords)]
        place(pad_bus, pad_chord(pad_voicing(key, chord), span, rng, voices=3, cents=9,
                                 attack=0.6, release=0.6), t0, 0.2, sr=PAD_SR)
        bm = bass_midi(key - 24, chord)
        if cfg["style"] == "pulse":
            for e in range(cfg["chord_bars"] * 8):
                bass_notes.append((t0 + e * beat / 2, 0.55 * beat / 2, bm, 0))
        else:
            bass_notes.append((t0, span - 0.05, bm, 0))
            for j in range(cfg["chord_bars"]):
                for st, k in ((0, 3 + (c + j) % 3), (10, 2 + (c + 2 * j) % 3)):
                    note = lead_note("bell", chord_tone(key, chord, k), 2 * step, rng)
                    place(bell_bus, note, t0 + j * barlen + st * step, 0.12)
    for bar in range(cfg["bars"]):
        for st in cfg["kick_steps"]:
            place(drums, soft_kick, bar * barlen + st * step, 0.45)
            kick_times.append(bar * barlen + st * step)
        if cfg["style"] == "pulse":
            for bt in range(4):
                place(drums, tick, bar * barlen + (bt + 0.5) * beat, 0.035, pan=0.3)
    if cfg["style"] == "pulse":
        bass = render_808(bass_notes, N, drive=1.3, decay=0.25, punch=0.0, attack=0.008,
                          second=0.05, top=600.0)
    else:
        bass = render_808(bass_notes, N, drive=1.2, decay=3.0, punch=0.0, attack=0.04,
                          second=0.06, top=500.0)
    pad = filt(upsample(pad_bus, N), hp(110) + lp4(cfg["pad_lp"])) * duck(N, kick_times, 0.25, 0.2)
    bells = filt(bell_bus, hp(300) + lp4(2600))
    verb = convolve(0.6 * pad + 0.9 * bells, ir)
    mix = drums + 0.5 * bass[None, :] + pad + bells + 0.35 * verb
    mix = filt(mix, hp(28))
    T = N - Ls
    mix[:, :T] += mix[:, Ls:Ls + T]          # fold the tail onto the head: loops cleanly
    return mix[:, :Ls], 0.5 * bass[:Ls]


def render_ident(cfg):
    """Rising detuned chord into an 808 hit and a three-note bell signature."""
    rng = np.random.default_rng(cfg["seed"])
    key, hit, L = cfg["key_root"], 1.5, 3.6
    N = int((L + 1.0) * SR)
    nr = int(hit * SR)
    p = secs(nr) / hit
    semis = -12.0 * (1.0 - p) ** 2
    chord = [key - 12, key - 5, key, key + 3, key + 7]
    rise = sum(unison(hz(m) * 2.0 ** (semis / 12.0), nr, rng, 5, 22, 1.0) for m in chord)
    rise = rise * p ** 1.6 / np.sqrt(len(chord))
    rise = fade_out(morph(filt_many(rise, [lp4(500), lp4(2000), lp(9000)]), 2.0 * p ** 1.2), 0.01)
    lead, drums, verb_send = (np.zeros((2, N)) for _ in range(3))
    place(lead, rise, 0.0, 0.45)
    place(lead, make_riser(rng, hit), 0.0, 0.12)
    place(drums, make_kick(rng, f_hi=180.0, decay=0.25, click=0.9), hit, 0.9)
    place(drums, make_kick(rng, f_hi=120.0, f_lo=38.0, tau=0.08, decay=0.9, click=0.3, length=2.5), hit, 0.5)
    clap = make_clap(rng)
    place(drums, clap, hit, 0.45)
    place(verb_send, clap, hit, 0.5)
    place(drums, make_hat(rng, 0.85, 0.8, tone=4200.0, length=2.5), hit, 0.2, pan=-0.2)
    for m in chord[1:]:
        place(lead, lead_note("supersaw", m, 0.3, rng), hit, 0.2)
    bells = np.zeros((2, N))
    for j, m in enumerate((key + 12, key + 15, key + 19)):
        place(bells, lead_note("bell", m, 0.3, rng), hit + 0.2 + 0.2 * j, 0.35)
    bass = render_808([(hit, L - hit, key - 36, 0)], N, drive=3.0, decay=1.2, punch=12.0, grit=0.25)
    lead = filt(lead, hp(120))
    verb = convolve(0.35 * lead + 0.6 * bells + verb_send, make_ir(rng, rt60=2.2, length=2.5))
    mix = np.tanh(1.3 * drums) / 1.3 + 0.62 * bass[None, :] + lead + bells + 0.35 * verb
    mix = filt(mix, hp(24))[:, :int(L * SR)]
    k = int(0.6 * SR)
    mix[:, -k:] *= np.cos(np.linspace(0, np.pi / 2, k)) ** 2
    return mix, bass[:int(L * SR)]


