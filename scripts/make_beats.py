def job_entry(name):
    if name in TRACKS:
        c = TRACKS[name]
        return "tracks", c["title"], c["bpm"], c["key"]
    if name in BEDS:
        c = BEDS[name]
        return "beds", c["title"], c["bpm"], c["key"]
    return "stingers", IDENT["title"], IDENT["bpm"], IDENT["key"]


def run_job(name, out_dir, work_dir):
    t0 = time.time()
    if name in TRACKS:
        mix, bass = render_track(TRACKS[name])
        target, limit = -16.0, True
    elif name in BEDS:
        mix, bass = render_bed(BEDS[name])
        target, limit = -26.0, False
    else:
        mix, bass = render_ident(IDENT)
        target, limit = -16.0, True
    t_render = time.time() - t0
    group, title, bpm, key = job_entry(name)
    peak_pre = float(20 * np.log10(np.max(np.abs(mix)) + 1e-12))
    bands = band_levels(mix)
    bass_bands = band_levels(bass)
    bass_share = float(10 * np.log10(np.sum(bass ** 2) * 2 / (np.sum(mix ** 2) + 1e-20) + 1e-12))
    mp3 = Path(out_dir) / f"{name}.mp3"
    info = master(mix, Path(work_dir) / f"{name}.wav", mp3, target, -1.5,
                  {"title": title, "artist": ARTIST, "album": "Exposure Radio",
                   "comment": LICENSE, "copyright": "MIT License"}, limit=limit)
    (Path(work_dir) / f"{name}.wav").unlink(missing_ok=True)
    res = measure(mp3)
    harm = sum(10 ** (v / 10) for k, v in bass_bands.items() if k != "sub")   # 808 energy above 120 Hz
    res.update(info, name=name, group=group, title=title, bpm=bpm, key=key, target=target,
               bands=bands, bass_harmonics_db=round(float(10 * np.log10(harm + 1e-12)), 1),
               bass_share_db=round(bass_share, 1), pre_peak_dbfs=round(peak_pre, 1),
               render_s=round(t_render, 1), total_s=round(time.time() - t0, 1))
    return res


ALL_JOBS = ["beat-01", "beat-02", "beat-03", "ident", "bed-news", "bed-learn"]


def write_manifest(out_dir, results):
    doc = {"tracks": [], "stingers": [], "beds": []}
    for name in ALL_JOBS:
        mp3 = Path(out_dir) / f"{name}.mp3"
        if name in results:
            dur = results[name]["duration"]
        elif mp3.exists():
            dur = measure(mp3)["duration"]
        else:
            continue
        group, title, bpm, key = job_entry(name)
        entry = {"id": name, "title": title, "artist": ARTIST, "audio": f"station/music/{name}.mp3",
                 "duration": dur, "bpm": bpm, "key": key, "license": LICENSE}
        if group == "beds":
            entry["loop"] = True
        doc[group].append(entry)
    (Path(out_dir) / "tracks.json").write_text(json.dumps(doc, indent=2) + "\n")


def check(res):
    """Sanity checks on loudness, duration and spectral balance; returns warnings."""
    w = []
    if abs(res["lufs"] - res["target"]) > 0.7:
        w.append(f"loudness {res['lufs']} LUFS vs target {res['target']}")
    if res["true_peak"] > -1.0:
        w.append(f"true peak {res['true_peak']} dBTP")
    if res["mode"] != "linear":
        w.append(f"loudnorm ran in {res['mode']} mode")
    if res["group"] == "tracks":
        if not 75 <= res["duration"] <= 92:
            w.append(f"duration {res['duration']} s")
        if not -9.0 <= res["bands"]["sub"] <= -0.3:
            w.append(f"sub band {res['bands']['sub']} dB of total (808 balance)")
        if res["bass_harmonics_db"] < -22:
            w.append("808 has too little harmonic content for small speakers")
    if res["group"] == "beds" and res["bands"]["pres"] > -14:
        w.append(f"bed presence band {res['bands']['pres']} dB is busy under speech")
    return w


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default=str(REPO / "web" / "station" / "music"), help="output directory")
    ap.add_argument("--only", nargs="*", choices=ALL_JOBS, help="render a subset (manifest keeps others)")
    ap.add_argument("--jobs", type=int, default=min(3, os.cpu_count() or 1), help="parallel renders")
    ap.add_argument("--work", default=None, help="scratch directory (default: system temp, honours TMPDIR)")
    args = ap.parse_args(argv)
    enc = subprocess.run(["ffmpeg", "-hide_banner", "-encoders"], capture_output=True, text=True).stdout
    if "libmp3lame" not in enc:
        sys.exit("ffmpeg with libmp3lame is required")
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    names = args.only or ALL_JOBS
    t0 = time.time()
    with tempfile.TemporaryDirectory(prefix="make_beats-", dir=args.work) as work:
        with ProcessPoolExecutor(max_workers=max(1, args.jobs)) as pool:
            futs = {n: pool.submit(run_job, n, str(out), work) for n in names}
            results = {n: f.result() for n, f in futs.items()}
    write_manifest(out, results)
    print(f"{'file':<10} {'title':<22} {'dur s':>6} {'LUFS':>6} {'dBTP':>6} {'bpm':>4} key"
          f"{'':<8} bands sub/low/mid/pres/air dB   render")
    warns = []
    for n in names:
        r = results[n]
        b = r["bands"]
        print(f"{n:<10} {r['title']:<22} {r['duration']:>6.2f} {r['lufs']:>6.1f} {r['true_peak']:>6.1f} "
              f"{r['bpm']:>4} {r['key']:<10} {b['sub']:>5}/{b['low']}/{b['mid']}/{b['pres']}/{b['air']}"
              f"  {r['render_s']:>5.1f}s (+{r['total_s'] - r['render_s']:.1f}s master, "
              f"drive {r['limiter_drive_db']} dB, 808 harm {r['bass_harmonics_db']} dB)")
        warns += [f"{n}: {m}" for m in check(r)]
    print(f"total wall time {time.time() - t0:.1f}s; wrote {out / 'tracks.json'}")
    for m in warns:
        print("WARNING:", m)
    return 1 if warns else 0


if __name__ == "__main__":
    sys.exit(main())
