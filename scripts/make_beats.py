def hz(midi):
    return 440.0 * 2.0 ** ((np.asarray(midi, dtype=float) - 69.0) / 12.0)


def secs(n):
    return np.arange(n) / SR


def fft_len(n):
    """Smallest 2^a*3^b*5^c >= n (fast FFT size)."""
    best = 1 << max(0, int(n - 1).bit_length())
    f5 = 1
    while f5 < best:
        f3 = f5
        while f3 < best:
            m = f3
            while m < n:
                m *= 2
            best = min(best, m)
            f3 *= 3
        f5 *= 5
    return best


def biquad(kind, f0, q=0.7071, gain_db=0.0):
    """RBJ audio-EQ-cookbook biquad coefficients (b, a), a[0] normalized to 1."""
    f0 = float(min(max(f0, 5.0), 0.47 * SR))
    w0 = TAU * f0 / SR
    cw, sw = np.cos(w0), np.sin(w0)
    al = sw / (2.0 * q)
    A = 10.0 ** (gain_db / 40.0)
    if kind == "lp":
        b, a = [(1 - cw) / 2, 1 - cw, (1 - cw) / 2], [1 + al, -2 * cw, 1 - al]
    elif kind == "hp":
        b, a = [(1 + cw) / 2, -(1 + cw), (1 + cw) / 2], [1 + al, -2 * cw, 1 - al]
    elif kind == "bp":
        b, a = [al, 0.0, -al], [1 + al, -2 * cw, 1 - al]
    elif kind == "peak":
        b, a = [1 + al * A, -2 * cw, 1 - al * A], [1 + al / A, -2 * cw, 1 - al / A]
    else:
        raise ValueError(kind)
    return np.array(b) / a[0], np.array(a) / a[0]


def lp(f, q=0.7071):
    return [biquad("lp", f, q)]


def lp4(f):  # 4th-order Butterworth (two cascaded biquads)
    return [biquad("lp", f, 0.5412), biquad("lp", f, 1.3066)]


def hp(f, q=0.7071):
    return [biquad("hp", f, q)]


def hp4(f):
    return [biquad("hp", f, 0.5412), biquad("hp", f, 1.3066)]


def bp(f, q):
    return [biquad("bp", f, q)]


def peak(f, q, gain_db):
    return [biquad("peak", f, q, gain_db)]


@lru_cache(maxsize=4)
def _unit_delay(nfft):
    return np.exp(-1j * TAU * np.arange(nfft // 2 + 1) / nfft)


def response(chain, nfft):
    """Complex frequency response of a biquad cascade on the rfft grid."""
    zi = _unit_delay(nfft)
    h = np.ones(nfft // 2 + 1, dtype=complex)
    for b, a in chain:
        h *= (b[0] + zi * (b[1] + zi * b[2])) / (1.0 + zi * (a[1] + zi * a[2]))
    return h


def filt_many(x, chains, tail=0.3):
    """Run x (mono or (2, n)) through several biquad cascades.

    The cascade is applied as its exact IIR transfer function in the frequency
    domain, zero-padded so the decaying tail does not wrap around. This is the
    same filter a sample-by-sample biquad computes, at numpy speed.
    """
    n = x.shape[-1]
    nfft = fft_len(n + int(tail * SR))
    if n > SR * 10:        # long buses: float32 FFT is plenty (-140 dB) and much faster
        x = x.astype(np.float32)
    X = np.fft.rfft(x, nfft, axis=-1)
    return [np.fft.irfft(X * response(c, nfft).astype(X.dtype), nfft, axis=-1)[..., :n]
            for c in chains]


def filt(x, chain, tail=0.3):
    return filt_many(x, [chain], tail)[0]


def convolve(x, ir):
    n = x.shape[-1]
    nfft = fft_len(n + ir.shape[-1])
    return np.fft.irfft(np.fft.rfft(x, nfft) * np.fft.rfft(ir, nfft), nfft)[..., :n]


def normalize(x, to=1.0):
    return x * (to / (np.max(np.abs(x)) + 1e-12))


def fade_out(x, dur):
    k = min(x.shape[-1], max(1, int(dur * SR)))
    x[..., -k:] *= np.linspace(1.0, 0.0, k)
    return x


def env_adsr(n, a, d, s, gate, r):
    """Linear attack, exponential decay to sustain, exponential release at gate."""
    t = secs(n)
    e = np.where(t < a, t / max(a, 1e-5), s + (1 - s) * np.exp(-(t - a) / max(d, 1e-5)))
    g = int(gate * SR)
    if g < n:
        e[g:] = e[g] * np.exp(-(t[g:] - t[g]) / r)
    return fade_out(e, 0.004)


def pan_gains(p):
    th = (np.asarray(p, dtype=float) + 1.0) * np.pi / 4.0
    return np.cos(th), np.sin(th)


def morph(versions, pos):
    """Crossfade a list of signals by a per-sample position 0..len-1."""
    out = np.zeros_like(versions[0])
    for k, v in enumerate(versions):
        out += v * np.clip(1.0 - np.abs(pos - k), 0.0, 1.0)
    return out


def place(bus, sig, t0, gain=1.0, pan=0.0, sr=SR):
    """Mix sig into bus at time t0 (s). Mono into stereo uses unity-centre panning."""
    s = int(round(t0 * sr))
    n = bus.shape[-1]
    if s >= n:
        return
    m = min(sig.shape[-1], n - s)
    if bus.ndim == 1:
        bus[s:s + m] += gain * sig[:m]
    elif sig.ndim == 1:
        gl, gr = pan_gains(pan)
        bus[0, s:s + m] += gain * np.sqrt(2) * gl * sig[:m]
        bus[1, s:s + m] += gain * np.sqrt(2) * gr * sig[:m]
    else:
        bus[:, s:s + m] += gain * sig[:, :m]


def duck(n, times, depth, release, attack=0.003):
    """Sidechain gain curve: dips by `depth` at each kick, recovers exponentially."""
    g = np.ones(n)
    L = int((attack + 6 * release) * SR)
    t = secs(L)
    curve = 1.0 - depth * np.where(t < attack, t / attack, np.exp(-(t - attack) / release))
    for tk in times:
        s = int(tk * SR)
        if s < n:
            e = min(n, s + L)
            g[s:e] = np.minimum(g[s:e], curve[:e - s])
    return g


def sliding_min(x, k):
    """Centred running minimum over odd window k (van Herk / Gil-Werman)."""
    h, n = k // 2, x.size
    m = -(-(n + 2 * h) // k) * k
    xp = np.full(m + k, np.inf)
    xp[h:h + n] = x
    blocks = xp.reshape(-1, k)
    pre = np.minimum.accumulate(blocks, axis=1).ravel()
    suf = np.minimum.accumulate(blocks[:, ::-1], axis=1)[:, ::-1].ravel()
    return np.minimum(suf[:n], pre[k - 1:k - 1 + n])


def box(x, k):
    """Centred moving average over odd window k."""
    h = k // 2
    c = np.cumsum(np.pad(x, (h + 1, h), mode="edge"))
    return (c[k:] - c[:-k]) / k


def limiter(x, ceiling=0.89, attack=0.004, release=0.08):
    """Look-ahead stereo-linked peak limiter; never exceeds `ceiling` (sample peak).

    Gain = running-min of the required gain, then box-smoothed within the same
    window, which provably stays at or below the required gain at every peak.
    A slow and a fast version are blended for low distortion on 808 tails.
    """
    pk = np.max(np.abs(x), axis=0)
    need = np.minimum(1.0, ceiling / np.maximum(pk, 1e-9))
    ka = 2 * int(attack * SR) + 1
    kr = 2 * int(release * SR) + 1
    fast = box(sliding_min(need, ka), ka)
    slow = box(sliding_min(fast, kr), kr)
    return x * (0.4 * fast + 0.6 * slow)


