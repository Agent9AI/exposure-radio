HAT_CELLS = {
    "q": [(0.0, 0.9)],
    "e": [(0.0, 0.9), (0.5, 0.6)],
    "s": [(0.0, 0.95), (0.25, 0.5), (0.5, 0.75), (0.75, 0.5)],
    "t3": [(0.0, 0.95), (1 / 3, 0.6), (2 / 3, 0.7)],                       # 8th triplets
    "t6": [(i / 6, 0.45 + 0.1 * i) for i in range(6)],                     # 16th triplets
    "r32": [(i / 8, 0.35 + 0.09 * i) for i in range(8)],                   # 1/32 roll
    "b32": [(0.0, 0.95), (0.25, 0.5), (0.5, 0.55), (0.625, 0.6), (0.75, 0.7), (0.875, 0.8)],
    "r64": [(0.0, 0.9), (0.25, 0.5)] + [(0.5 + i / 16, 0.35 + 0.08 * i) for i in range(8)],
}


def hat_events(rng, rolls, density, phrase_end):
    names, weights = zip(*rolls)
    weights = np.array(weights, float) / sum(weights)
    events = []
    for b in range(4):
        if density == "sparse":
            cell = "e"
        elif density == "half":
            cell = "q"
        else:
            roll = b == 3 or (density == "busy" and b == 1) or (phrase_end and b == 2)
            if roll:
                cell = str(rng.choice(names, p=weights))
            else:
                cell = "s" if rng.random() < (0.8 if density == "busy" else 0.6) else "e"
        hits = HAT_CELLS[cell]
        pitched = cell in ("t6", "r32", "r64", "b32") and rng.random() < 0.5
        for i, (off, vel) in enumerate(hits):
            pi = min(2, int(3 * i / len(hits))) if pitched else 0
            events.append((b + off, vel * rng.uniform(0.86, 1.0), pi))
    return events


