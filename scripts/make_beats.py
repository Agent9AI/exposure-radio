def blep_saw(p, dt):
    """Band-limited sawtooth (PolyBLEP) from phase p in [0,1) and increment dt."""
    dt = np.broadcast_to(dt, p.shape)
    y = 2.0 * p - 1.0
    m = p < dt
    t = p[m] / dt[m]
    y[m] -= 2 * t - t * t - 1
    m = p > 1.0 - dt
    t = (p[m] - 1.0) / dt[m]
    y[m] -= t * t + 2 * t + 1
    return y


def unison(freq, n, rng, voices=7, cents=25.0, width=0.9, shape="saw", pw=0.5, sr=SR):
    """Detuned unison oscillator stack, spread across the stereo field -> (2, n).

    freq may be a scalar or a per-sample array (for glides).
    """
    offs = np.linspace(-1, 1, voices) if voices > 1 else np.zeros(1)
    ratios = 2.0 ** (offs * cents / 1200.0)
    ph0 = rng.random(voices)
    f = np.asarray(freq, dtype=float)
    if f.ndim == 0:
        dt = (f * ratios / sr)[:, None]
        p = (ph0[:, None] + np.arange(n)[None, :] * dt) % 1.0
    else:
        cyc = np.concatenate([[0.0], np.cumsum(f[:-1])]) / sr
        dt = f[None, :] * ratios[:, None] / sr
        p = (ph0[:, None] + cyc[None, :] * ratios[:, None]) % 1.0
    w = blep_saw(p, dt)
    if shape == "pulse":
        w = 0.5 * (w - blep_saw((p + pw) % 1.0, dt))
    gains = np.where(np.abs(offs) < 1e-9, 1.0, 0.75) / np.sqrt(voices)
    gl, gr = pan_gains(offs * width)
    return np.stack([(gains * gl) @ w, (gains * gr) @ w]) * np.sqrt(2)


def lead_note(kind, midi, dur, rng):
    """One lead note -> (2, n). kinds: supersaw, pulse (rage pluck), bell (FM)."""
    f = float(hz(midi))
    if kind == "supersaw":
        n = int((dur + 0.35) * SR)
        y = unison(f, n, rng, 7, 26, 0.9) + 0.35 * unison(f / 2, n, rng, 1, 0, 0)
        return 0.9 * y * env_adsr(n, 0.003, 0.18, 0.55, dur, 0.09)
    if kind == "pulse":
        n = int((dur + 0.25) * SR)
        y = unison(f, n, rng, 3, 14, 0.7, shape="pulse", pw=0.32)
        y += 0.3 * unison(2 * f, n, rng, 1, 0, 0, shape="pulse", pw=0.5)
        return 0.8 * np.tanh(2.2 * y) * env_adsr(n, 0.001, 0.09, 0.3, dur, 0.05)
    if kind == "bell":
        n = int(min(dur + 0.9, 2.2) * SR)
        t = secs(n)
        idx = 2.2 * np.exp(-t / 0.12) + 0.35
        y = np.sin(TAU * f * t + idx * np.sin(TAU * f * t)) * np.exp(-t / 0.7)
        y += 0.12 * np.sin(TAU * f * t + 1.5 * np.exp(-t / 0.05) * np.sin(TAU * 3.5 * f * t)) * np.exp(-t / 0.3)
        y += 0.2 * np.sin(TAU * 4 * f * t) * np.exp(-t / 0.035)
        y *= np.minimum(1.0, t / 0.0015)
        g = int((dur + 0.3) * SR)
        if g < n:
            y[g:] *= np.exp(-(t[g:] - t[g]) / 0.12)
        gl, gr = pan_gains(rng.uniform(-0.35, 0.35))
        return 0.7 * np.sqrt(2) * np.stack([gl * y, gr * y]) * fade_out(np.ones(n), 0.01)
    raise ValueError(kind)


PAD_SR = SR // 4   # pads are low-passed near 1 kHz, so they are synthesized at quarter rate


def pad_chord(midis, dur, rng, voices=3, cents=12, attack=0.25, release=0.3):
    """Detuned saw chord at PAD_SR -> (2, n); mix into a PAD_SR bus, then upsample()."""
    n = int((dur + 1.0) * PAD_SR)
    y = sum(unison(hz(m), n, rng, voices, cents, 1.0, sr=PAD_SR) for m in midis)
    e = env_adsr(int((dur + 1.0) * SR), attack, 0.5, 0.85, dur, release)[::4][:n]
    return y * e / np.sqrt(len(midis))


def upsample(x, n):
    """Linear-interpolate a PAD_SR bus to SR (images sit far above the pad low-pass)."""
    t = np.arange(n) * (PAD_SR / SR)
    src = np.arange(x.shape[-1])
    return np.stack([np.interp(t, src, ch) for ch in x])


def render_808(notes, n_total, drive=2.8, decay=1.4, punch=12.0, glide=0.07, attack=0.002,
               second=0.12, top=2800.0, grit=0.0):
    """Sine 808 with pitch punch, legato glides and tanh saturation -> mono.

    notes: (start_s, dur_s, midi, glide_from_previous). A glide note continues the
    previous note without retriggering and slides its pitch over `glide` seconds.
    The 2nd harmonic plus saturation make it audible on small speakers; `grit`
    adds a parallel hard-clipped layer, high-passed so only its buzz is heard.
    """
    out = np.zeros(n_total)
    dirt = np.zeros(n_total) if grit else None
    phrases = []
    for nt in sorted(notes, key=lambda v: v[0]):
        if nt[3] and phrases and abs(phrases[-1][-1][0] + phrases[-1][-1][1] - nt[0]) < 1e-4:
            phrases[-1].append(nt)
        else:
            phrases.append([nt])
    for ph in phrases:
        s0 = int(round(ph[0][0] * SR))
        n = int(round((ph[-1][0] + ph[-1][1]) * SR)) - s0
        if n <= 0 or s0 >= n_total:
            continue
        f = np.empty(n)
        prev = None
        for st, du, m, _ in ph:
            a = int(round(st * SR)) - s0
            b = n if (st, du) == ph[-1][:2] else int(round((st + du) * SR)) - s0
            tt = secs(b - a)
            ft = float(hz(m))
            if prev is None:
                f[a:b] = ft * 2.0 ** ((punch / 12.0) * np.exp(-tt / 0.010))
            else:
                k = np.clip(tt / glide, 0.0, 1.0)
                k = k * k * (3 - 2 * k)
                f[a:b] = prev * (ft / prev) ** k
            prev = ft
        t = secs(n)
        phase = TAU * np.concatenate([[0.0], np.cumsum(f[:-1])]) / SR
        x = np.sin(phase) + second * np.sin(2 * phase + 0.3)
        amp = np.exp(-t / decay) * np.minimum(1.0, t / attack)
        amp = fade_out(amp, 0.015)
        y = np.tanh(drive * amp * x) / np.tanh(drive)
        m = min(n, n_total - s0)
        out[s0:s0 + m] += y[:m]
        if grit:
            dirt[s0:s0 + m] += np.tanh(9.0 * amp[:m] * x[:m])
    if grit:
        return filt(out + grit * filt(dirt, hp4(180)), hp(28) + lp4(top))
    return filt(out, hp(28) + lp4(top))


def make_kick(rng, f_hi=165.0, f_lo=47.0, tau=0.032, decay=0.2, click=0.7, length=0.6, drive=2.2):
    n = int(length * SR)
    t = secs(n)
    f = f_lo + (f_hi - f_lo) * np.exp(-t / tau)
    body = np.sin(TAU * np.cumsum(f) / SR) * np.exp(-t / decay) * np.minimum(1.0, t / 0.0007)
    nz = normalize(filt(rng.standard_normal(n) * np.exp(-t / 0.0035), bp(3800, 0.9)))
    clk = np.sin(TAU * 1600 * t) * np.exp(-t / 0.0025)
    y = np.tanh(drive * (body + click * (0.6 * nz + 0.5 * clk))) / np.tanh(drive)
    return fade_out(y, 0.03)


def make_clap(rng, length=0.7):
    n = int(length * SR)
    t = secs(n)
    env = np.zeros(n)
    for k, off in enumerate((0.0, 0.0085, 0.0175, 0.027)):
        tt = t - off
        env += np.where(tt >= 0, np.exp(-np.maximum(tt, 0) / 0.0042), 0.0) * (1 - 0.12 * k)
    tt = t - 0.027
    env += np.where(tt >= 0, 0.75 * np.exp(-np.maximum(tt, 0) / 0.13), 0.0)
    y = filt(rng.standard_normal(n) * env, bp(1250, 0.7) + hp(500) + peak(2600, 1.0, 4.0))
    return fade_out(normalize(y), 0.02)


def make_snare(rng, length=0.5):
    n = int(length * SR)
    t = secs(n)
    f = 180 + 70 * np.exp(-t / 0.008)
    body = np.sin(TAU * np.cumsum(f) / SR) * np.exp(-t / 0.06)
    nz = normalize(filt(rng.standard_normal(n), hp(1500) + peak(5000, 1.0, 3.0))) * np.exp(-t / 0.11)
    return fade_out(normalize(np.tanh(1.5 * (0.7 * body + 0.9 * nz))), 0.02)


HAT_FREQS = np.array([205.3, 304.4, 369.6, 522.7, 540.0, 800.0]) * 1.9


def make_hat(rng, decay, rate=1.0, tone=7000.0, length=None):
    """Metallic hat: six inharmonic squares plus noise, high-passed, fast envelope."""
    n = int((length or min(1.6, decay * 7 + 0.02)) * SR)
    t = secs(n)
    metal = np.sign(np.sin(TAU * (HAT_FREQS * rate)[:, None] * t[None, :]
                           + TAU * rng.random(6)[:, None])).sum(0) / 6.0
    src = 0.55 * metal + 0.7 * rng.standard_normal(n)
    y = filt(src, hp4(tone * rate) + peak(10500 * min(rate, 1.3), 1.2, 4.0))
    env = np.exp(-t / decay) * np.minimum(1.0, t / 0.0004)
    return normalize(fade_out(y * env, 0.005))


def make_riser(rng, dur):
    """Noise sweep: band-passed noise morphing upward with a rising swell -> (2, n)."""
    n = int(dur * SR)
    p = secs(n) / dur
    vs = filt_many(rng.standard_normal((2, n)), [bp(f, 1.4) for f in (400, 1200, 3500, 9000)])
    vs = [normalize(v) for v in vs]
    return normalize(fade_out(morph(vs, 3.0 * p) * p ** 2.2, 0.01))


def make_ir(rng, rt60=1.7, length=2.2, predelay=0.014):
    """Stereo reverb impulse: decorrelated noise, darker as it decays."""
    n = int(length * SR)
    t = secs(n)
    dark, bright = filt_many(rng.standard_normal((2, n)), [lp(3000), hp(3000)])
    ir = dark * 10 ** (-3 * t / rt60) + 0.6 * bright * 10 ** (-3 * t / (rt60 * 0.35))
    ir *= 1.0 - np.exp(-t / 0.018)
    ir = filt(ir, hp(200))
    pd = int(predelay * SR)
    ir = np.pad(ir, ((0, 0), (pd, 0)))[:, :n]
    return ir / np.sqrt(np.mean(np.sum(ir ** 2, axis=1)))


def pingpong(x, delay, fb=0.42, taps=6):
    mono = x.mean(0)
    n = mono.size
    out = np.zeros((2, n))
    for k in range(1, taps + 1):
        d = int(round(k * delay * SR))
        if d >= n:
            break
        out[(k - 1) % 2, d:] += fb ** (k - 1) * mono[:n - d]
    return filt(out, hp(350) + lp(3200))


