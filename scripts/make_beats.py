QUALITIES = {"m": (0, 3, 7), "M": (0, 4, 7), "m7": (0, 3, 7, 10), "M7": (0, 4, 7, 11),
             "m9": (0, 3, 7, 10, 14)}


def chord_tone(key_root, chord, k):
    """k-th triad tone counted from the chord tone nearest the key root."""
    root, q = chord
    tones = sorted({key_root + root + iv + 12 * o for iv in QUALITIES[q][:3] for o in range(-3, 4)})
    i0 = min(range(len(tones)), key=lambda i: (abs(tones[i] - key_root), tones[i]))
    return tones[i0 + k]


def pad_voicing(key_root, chord, lo=-10, hi=4):
    root, q = chord
    out = []
    for iv in QUALITIES[q]:
        m = key_root + root + iv
        while m < key_root + lo:
            m += 12
        while m > key_root + hi:
            m -= 12
        out.append(m)
    return sorted(set(out))


def bass_midi(base, chord, floor=24):
    m = base + ((chord[0] + 6) % 12) - 6
    return m + 12 if m < floor else m


